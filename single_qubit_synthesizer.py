import numpy as np
from qiskit import QuantumCircuit
from qiskit.quantum_info import Operator

def synthesize_single_qubit(U):
  I = np.eye(2)

  U_dagger = np.conj(U).T

  if not np.allclose(U @ U_dagger , I):

    raise ValueError("is not Unitary!")


  gamma = 1/2 * np.angle(np.linalg.det(U))

  V = np.exp(-1j * gamma) * U

  a = V[0,0]

  b = V[0,1]


  if np.isclose(np.abs(b) , 0):

    alpha = -2 * np.angle(a)

    beta = 0
    delta = 0

  elif np.isclose(np.abs(a) , 0):
    alpha = -2 * np.angle(-b)
    beta = np.pi
    delta = 0


  else:
    beta = np.arctan2(np.abs(b) , np.abs(a)) * 2

    alpha = -(np.angle(a) + np.angle(-b))

    delta = -(np.angle(a) - np.angle(-b))

  qc = QuantumCircuit(1)

  qc.rz(delta , 0)
  qc.ry(beta , 0)
  qc.rz(alpha , 0)
  qc.global_phase = gamma

  return qc

# Enter here your Test Matrix

U = np.array([[0, -1],[1,  0]], dtype=complex)

qc = synthesize_single_qubit(U)

print(np.allclose(U, Operator(qc).data))

